/** 대소문자·띄어쓰기·따옴표·괄호·구두점 차이는 무시 */
export function normalize(s: string): string {
  return s
    .toLowerCase()
    .replace(/[\s'"`“”‘’()[\]{}.,;:·\-_/]/g, "");
}

function normalizeAnyOrder(s: string): string {
  return s
    .split(/[,，、]/)
    .map(normalize)
    .filter(Boolean)
    .sort()
    .join("|");
}

export function isCorrect(q: ExamQ, input: string): boolean {
  if (!input.trim()) return false;
  if (q.anyOrder) {
    const got = normalizeAnyOrder(input);
    return q.a.some((a) => normalizeAnyOrder(a) === got);
  }
  const got = normalize(input);
  return q.a.some((a) => normalize(a) === got);
}

export const answerOf = (q: ExamQ) => q.show ?? q.a[0];
